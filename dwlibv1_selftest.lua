local function check(cond, name)
    if not cond then error("selftest failed: " .. tostring(name), 0) end
end

check(type(Library) == "table", "Library table")
check(type(Library.CreateWindow) == "function", "CreateWindow")
check(type(Library.Notification) == "function", "Notification")
check(type(Library.Dialog) == "function", "Dialog")
check(type(Library.GetConfig) == "function", "GetConfig")
check(type(Library.LoadConfig) == "function", "LoadConfig")
check(type(Library.ApplyThemePreset) == "function", "ApplyThemePreset")
check(type(Library.ChangeTheme) == "function", "ChangeTheme")
check(Library.Theme ~= nil and Library.Theme.Accent ~= nil, "Theme.Accent")
check(Library.Presets ~= nil and Library.Presets.DroidRed ~= nil, "Presets.DroidRed")
check(type(Library.Sections.Toggle) == "function", "Toggle")
check(type(Library.Sections.Button) == "function", "Button")
check(type(Library.Sections.Slider) == "function", "Slider")
check(type(Library.Sections.Dropdown) == "function", "Dropdown")
check(type(Library.Sections.Label) == "function", "Label")
check(type(Library.Sections.Textbox) == "function", "Textbox")
check(type(Library.Sections.Colorpicker) == "function", "Colorpicker")
check(type(Library.Sections.Keybind) == "function", "Keybind")
check(type(Library.Watermark) == "function", "Watermark")
check(type(Library.KeybindList) == "function", "KeybindList")
check(type(Library.ESPPreview) == "function", "ESPPreview")
check(type(Library.ToggleButton) == "function", "ToggleButton")
check(type(Library.AttachTooltip) == "function", "AttachTooltip")
check(type(Library.ApplyFlags) == "function", "ApplyFlags")
check(type(Library.SaveConfig) == "function", "SaveConfig")
check(type(Library.HasConfig) == "function", "HasConfig")
check(type(Library.ExportConfigString) == "function", "ExportConfigString")
check(type(Library.ImportConfigString) == "function", "ImportConfigString")
check(type(Library.CopyConfigToClipboard) == "function", "CopyConfigToClipboard")
check(type(Library.PasteConfigFromClipboard) == "function", "PasteConfigFromClipboard")
check(type(Library.SetAutoSave) == "function", "SetAutoSave")
check(type(Library.DisableAutoSave) == "function", "DisableAutoSave")
check(type(Library.IsAutoSaveEnabled) == "function", "IsAutoSaveEnabled")
check(type(Library.IgnoreFlag) == "function", "IgnoreFlag")
check(type(Library.UnignoreFlag) == "function", "UnignoreFlag")
check(type(Library.IsFlagIgnored) == "function", "IsFlagIgnored")
check(type(Library.ConfigIgnore) == "table", "ConfigIgnore")
check(Library:IsFlagIgnored("__cfg_name") == true, "ignore __cfg_name")
check(type(Library.LoadAutoload) == "function", "LoadAutoload")
check(type(Library.DeleteConfig) == "function", "DeleteConfig")
check(type(Library.ShowPopup) == "function", "ShowPopup")
check(type(Library.ClosePopups) == "function", "ClosePopups")
check(type(Library.BringToFront) == "function", "BringToFront")
check(type(Library.CreateHomePage) == "function", "CreateHomePage")
check(type(Library.SetUIScale) == "function", "SetUIScale")
check(type(Library.PreviewUIScale) == "function", "PreviewUIScale")
check(type(Library.ClearUIScalePreview) == "function", "ClearUIScalePreview")
check(type(Library.GetIcon) == "function", "GetIcon")
check(type(Library.IconMap) == "table" and Library.IconMap["house"] ~= nil, "IconMap.house")
check(Library:GetIcon("house") == Library.IconMap["house"], "GetIcon(lucide)")
check(Library:GetIcon("rbxassetid://123") == "rbxassetid://123", "GetIcon(passthrough)")
check(Library:GetIcon("nope-not-an-icon") == nil, "GetIcon(unknown)")
check(Library.AnimationsEnabled == true, "AnimationsEnabled default")
check(Library.TooltipsEnabled == true, "TooltipsEnabled default")
check(Library.NotifDuration == 4, "NotifDuration default")
check(type(Library.SetBackgroundImage) == "function", "SetBackgroundImage")
check(type(Library.OnUnload) == "function", "OnUnload")

local okTheme = Library:ApplyThemePreset("DroidRed")
check(okTheme == true, "ApplyThemePreset(DroidRed)")
check(Library:ChangeTheme("Accent", Color3.fromRGB(1, 2, 3)) == true, "ChangeTheme")
check(Library:ApplyThemePreset("DroidRed") == true, "restore theme")

local cfg = Library:GetConfig()
check(type(cfg) == "string" and #cfg > 2, "GetConfig json")
check(Library:LoadConfig(cfg) == true, "LoadConfig roundtrip")

Library:IgnoreFlag("selftest_transient")
Library.Flags.selftest_transient = "no-save"
local cfg2 = Library:ExportConfigString()
check(string.find(cfg2, "selftest_transient") == nil, "ignore filters export")
Library:UnignoreFlag("selftest_transient")
check(Library:IsFlagIgnored("selftest_transient") == false, "unignore")
check(Library:ImportConfigString(cfg) == true, "ImportConfigString roundtrip")
Library:SetAutoSave("selftest_autosave", 30)
check(Library:IsAutoSaveEnabled() == true, "autosave enabled")
check(Library:GetAutoSaveName() == "selftest_autosave", "autosave name")
Library:DisableAutoSave()
check(Library:IsAutoSaveEnabled() == false, "autosave disabled")

print("RESULT: selftest passed")
return true
